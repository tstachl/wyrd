#!/usr/bin/env bash
# tests/drive/drive-service-entry.sh — entryPoint for
# [tasks.wyrd-drive-e2e]: the host built the wyrd-drive-vm runner from
# this revision, provisioned the drive box, booted it, and waited.
# This entry reads the provision datum (never derives), holds the
# provision lock, publishes the run env the wrapper guard parses,
# and execs bats on the drive-service suite. Same datum discipline
# as tests/gate/gate-entry.sh; a task with different roles needs its
# own entry, not a flag.
#
# Usage: run by the gate task unit, never by hand.
set -euo pipefail

PROVISION_DIR="${GATE_TASK_PROVISION_DIR:?drive-service-entry.sh: GATE_TASK_PROVISION_DIR is not set}"
[ -d "$PROVISION_DIR" ] || { echo "drive-service-entry.sh: provision dir is missing" >&2; exit 1; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
REV="$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo "staged-tree (rev in task run record)")"
echo "drive-service-entry.sh: revision under test: $REV"

policy() { # <name>
  local file="$PROVISION_DIR/$1" value=""
  [ -f "$file" ] || { echo "drive-service-entry.sh: provision datum is missing: $1" >&2; return 1; }
  value="$(cat "$file")"
  [ -n "$value" ] || { echo "drive-service-entry.sh: provision datum is empty: $1" >&2; return 1; }
  printf '%s' "$value"
}

STATE_DIR="$(policy state-dir)" || exit 1
LOCK_FILE="$(policy lock-file)" || exit 1
SUBNET="$(policy subnet)" || exit 1
SSH_USER="$(policy ssh-user)" || exit 1
[[ "$SUBNET" =~ ^([0-9]{1,3}\.){2}[0-9]{1,3}$ ]] || { echo "drive-service-entry.sh: subnet out of bounds: $SUBNET" >&2; exit 1; }
IFS=. read -ra _octets <<<"$SUBNET"
for octet in "${_octets[@]}"; do
  [ "$octet" -le 255 ] || { echo "drive-service-entry.sh: subnet octet out of bounds: $SUBNET" >&2; exit 1; }
done
unset _octets octet
[[ "$SSH_USER" =~ ^[a-z_][a-z0-9_-]{0,31}$ ]] || { echo "drive-service-entry.sh: ssh user out of bounds: $SSH_USER" >&2; exit 1; }
ROLES_FILE="$PROVISION_DIR/roles"
[ -f "$ROLES_FILE" ] || { echo "drive-service-entry.sh: provision datum is missing: roles" >&2; exit 1; }

SSH_KEY="$STATE_DIR/sshkey"
[ -f "$SSH_KEY" ] || { echo "drive-service-entry.sh: ssh key is missing at $SSH_KEY (host provisions it)" >&2; exit 1; }
RUN="$STATE_DIR/run"
[ -d "$RUN" ] || { echo "drive-service-entry.sh: run tree is missing at $RUN (host provisions it)" >&2; exit 1; }

# The drive box's endpoint from the published roles (name tap octet
# ssh-flag runner, `|`-separated). Fails fast on shape violations.
DRIVE_SSH=""
while IFS= read -r record || [ -n "$record" ]; do
  read -ra fields <<<"$record"
  [ "${#fields[@]}" -eq 5 ] || { echo "drive-service-entry.sh: role out of bounds: $record" >&2; exit 1; }
  [[ "${fields[2]}" =~ ^[0-9]{1,3}$ ]] && [ "${fields[2]}" -ge 1 ] && [ "${fields[2]}" -le 254 ] \
    || { echo "drive-service-entry.sh: role octet out of bounds: $record" >&2; exit 1; }
  case "${fields[3]}" in ssh|-) ;; *) { echo "drive-service-entry.sh: ssh flag out of bounds: $record" >&2; exit 1; } ;; esac
  if [ "${fields[0]}" = "drive" ] && [ "${fields[3]}" = "ssh" ]; then DRIVE_SSH="$SSH_USER@$SUBNET.${fields[2]}"; fi
done < <(tr '|' '\n' <"$ROLES_FILE")
[ -n "$DRIVE_SSH" ] || { echo "drive-service-entry.sh: roles name no ssh drive box" >&2; exit 1; }

# Run environment, parsed by the wrapper guard (token and pid) and
# sourced by nothing in-guest: every assertion runs from the host
# over ssh, so this file is the run record, not guest config.
TOKEN="$(head -c16 /dev/urandom | od -An -tx1 | tr -d ' \n')"
{
  echo "# Generated by tests/drive/drive-service-entry.sh; parsed by the wrapper guard, never sourced in-guest."
  printf 'DRIVE_SSH=%q\n' "$DRIVE_SSH"
  printf 'WYRD_E2E_TOKEN=%s\n' "$TOKEN"
  printf 'WYRD_E2E_PID=%s\n' "$$"
} > "$RUN/e2e-env.sh"
chmod 0644 "$RUN/e2e-env.sh"

# Hold the provision lock for the suite's lifetime, like the gate entry.
exec 9>"$LOCK_FILE"
acquired=""
for _ in $(seq 1 60); do
  if flock -n 9 2>/dev/null; then acquired=1; break; fi
  sleep 1
done
[[ -n "$acquired" ]] || { echo "drive-service-entry.sh: another run holds $LOCK_FILE" >&2; exit 2; }

export WYRD_E2E_TOKEN="$TOKEN" WYRD_E2E_LOCK="$LOCK_FILE"
export STATE_DIR SSH_KEY DRIVE_SSH

command -v bats >/dev/null || { echo "drive-service-entry.sh: bats is not on PATH" >&2; exit 1; }
command -v timeout >/dev/null || { echo "drive-service-entry.sh: timeout is not on PATH" >&2; exit 1; }
command -v flock >/dev/null || { echo "drive-service-entry.sh: flock is not on PATH" >&2; exit 1; }
command -v ssh >/dev/null || { echo "drive-service-entry.sh: ssh is not on PATH" >&2; exit 1; }
echo "drive-service-entry.sh: bats $(bats --version 2>/dev/null || echo unknown)"
SSH_OPTS="-i $SSH_KEY -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o ConnectTimeout=10 -o BatchMode=yes -o LogLevel=ERROR"

# The guest must answer before anything else runs: without this,
# every later ssh fails identically and the failure looks like a
# test defect instead of missing infrastructure.
timeout 120 ssh $SSH_OPTS "$DRIVE_SSH" true \
  || { echo "drive-service-entry.sh: guest ssh is unreachable at $DRIVE_SSH" >&2; exit 1; }

# Provision test secrets and two fresh drives: harness work, not
# service config. The module supervises; the entry owns the secrets.
# This lives here (not in bats setup_file) so it runs under plain
# bash with no dependence on any runner's setup_file semantics, and
# so an unwrapped direct bats invocation can never mutate the guest
# (the bats file contains no provisioning path at all).
# shellcheck disable=SC2086
timeout 120 ssh $SSH_OPTS "$DRIVE_SSH" 'set -e
  sudo mkdir -p /etc/wyrd /var/lib/wyrd/demo /var/lib/wyrd/laptop /mnt/wyrd
  # sudo resolves the hostname on every invocation; the isolated
  # guest has no DNS, so pin it or every sudo below stalls on the
  # resolver and burns the ssh timeout instead of asserting.
  grep -q wyrd-drive /etc/hosts || echo "127.0.0.1 wyrd-drive" | sudo tee -a /etc/hosts >/dev/null
  head -c32 /dev/urandom | sudo tee /etc/wyrd/identity >/dev/null
  sudo chmod 600 /etc/wyrd/identity
  printf e2e-test-passphrase | sudo tee /etc/wyrd/passphrase >/dev/null
  sudo chmod 600 /etc/wyrd/passphrase
  sudo wyrd init /var/lib/wyrd/demo --identity-file /etc/wyrd/identity --passphrase-file /etc/wyrd/passphrase
  sudo wyrd init /var/lib/wyrd/laptop --identity-file /etc/wyrd/identity --passphrase-file /etc/wyrd/passphrase' \
  || { echo "drive-service-entry.sh: provisioning failed" >&2; exit 1; }

# Controlled boot with retained fixtures: the reboot proves the
# units activate at boot with secrets and drives already in place.
# A manual start here would mask a missing boot enablement.
OLD_BOOT="$(timeout 120 ssh $SSH_OPTS "$DRIVE_SSH" 'cat /proc/sys/kernel/random/boot_id')" || { echo "drive-service-entry.sh: cannot read guest boot id" >&2; exit 1; }
timeout 120 ssh $SSH_OPTS "$DRIVE_SSH" 'sudo systemctl reboot' || true
echo "drive-service-entry.sh: reboot requested, waiting for the guest to go down (up to 120s)"
DOWN=""
for _ in $(seq 1 24); do
  if ! timeout 20 ssh $SSH_OPTS "$DRIVE_SSH" true 2>/dev/null; then DOWN=1; break; fi
  sleep 5
done
[[ -n "$DOWN" ]] || { echo "drive-service-entry.sh: guest never went down for reboot" >&2; exit 1; }
echo "drive-service-entry.sh: guest is down, waiting for it to come back with a new boot id (up to 300s)"
BOOTED=""
for _ in $(seq 1 60); do
  # shellcheck disable=SC2086
  NEW_BOOT="$(timeout 120 ssh $SSH_OPTS "$DRIVE_SSH" 'cat /proc/sys/kernel/random/boot_id' 2>/dev/null || true)"
  NEW_BOOT="$(printf '%s' "$NEW_BOOT" | tr -d ' \n')"
  if [[ -n "$NEW_BOOT" && "$NEW_BOOT" != "$OLD_BOOT" ]]; then BOOTED=1; break; fi
  sleep 5
done
[[ -n "$BOOTED" ]] || { echo "drive-service-entry.sh: guest went down for reboot but never came back with a new boot id" >&2; exit 1; }
echo "drive-service-entry.sh: guest rebooted ($OLD_BOOT -> $NEW_BOOT)"

exec bats "$ROOT/tests/drive/drive-service.bats"
